#Классификация возрастов

# ввод возраста
age = int(input("Введите возраст: "))
#Вывод класса возраста с помощью оператора if
if age < 0:
    print("Введен некорректный возраст")
elif age <= 12:
    print("Ребенок")
elif age <= 17:
    print("Подросток")
elif age <= 64:
    print("Взрослый")
else:
    print("Пожилой")

